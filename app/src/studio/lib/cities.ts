const fold = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();
const BY_NAME = new Map(CITIES.map(([city, country, zone]) => [fold(city), { city, country, zone }]));

export const CITY_NAMES = CITIES.map(([city]) => city);

/** The country and time zone for a city typed in (accents and case ignored), if it's one we know. */
export const citySuggestion = (typed: string) => BY_NAME.get(fold(typed)) ?? null;

/** Every IANA time zone the browser knows, for the time zone field's list. */
